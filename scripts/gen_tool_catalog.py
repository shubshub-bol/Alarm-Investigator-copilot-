"""Generate docs/mcp-tool-catalog.md from the real MCP server.

    uv run python scripts/gen_tool_catalog.py

Runs in memory (MCP client -> our MCP server -> connector -> simulator, no network), lists the tools and
calls each one with an example, so every schema, endpoint and example response in the catalog comes from
the code itself and cannot drift from it. Re-run after changing a tool.
"""

