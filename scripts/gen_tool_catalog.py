OUT = Path(__file__).resolve().parents[1] / "docs" / "mcp-tool-catalog.md"
TOKEN = "catalog-token"  # noqa: S105 - in-memory example run, not a secret
TRACE = {"trace_id": "trace-catalog-0001"}
MAX_ITEMS = 2  # list items kept in example responses
MAX_TEXT = 160  # characters kept in long example strings

# What each id-based tool needs is looked up first, so the examples use real ids.
