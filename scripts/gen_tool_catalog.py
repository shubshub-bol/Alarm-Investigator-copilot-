COMMON = """\
# MCP tool catalog

The Alarm Management MCP server (`mcp-servers/alarm-management/alarm_mcp`) exposes the Alarm Management API as
13 read-only MCP tools. This file is generated by `scripts/gen_tool_catalog.py`, which calls every tool through a
real MCP client, so the schemas and examples below are the server's actual behaviour.

## Running the server

| | |
|---|---|
| Start (HTTP) | `uv run python -m alarm_mcp` (streamable HTTP on `MCP_HOST:MCP_PORT`, default `127.0.0.1:9000`) |
| MCP endpoint | `/mcp` |
| Start (stdio) | `uv run python -m alarm_mcp --stdio` - for MCP Inspector or a desktop MCP client |
| Health | `GET /health` (no token) returns `{"status": "ok", "tools": 13, ...}` |
| Docker | the `alarm-mcp` service in `docker-compose.yml` (port 9000 on localhost) |
| Settings | `MCP_*` for the server, `ALARM_API_*` for its Alarm API connection (see `.env.example`) |

## Behaviour shared by every tool

**Authentication.** Two separate boundaries:

1. *Client to MCP server.* Every request to `/mcp` must carry `Authorization: Bearer <MCP_AUTH_TOKEN>`, compared in
   constant time; anything else gets HTTP 401 before MCP is involved. The server refuses to start without a token
   unless `MCP_ALLOW_UNAUTHENTICATED=true` is set explicitly for local experiments. DNS-rebinding protection only
   accepts the hosts in `MCP_ALLOWED_HOSTS` (`127.0.0.1`, `localhost`, `alarm-mcp`).
2. *MCP server to Alarm API.* The connector sends `Authorization: Bearer <ALARM_API_TOKEN>` on every call. Both
   tokens are `SecretStr` values: they never appear in logs, tool results or error messages.

**Source-system operation.** Each tool wraps one Alarm API endpoint (`calculate_kpi` wraps two). The exact calls a
tool made are returned in `meta.api_calls` with method, path, status code, attempts and duration.

**Trace metadata.** A client can pass `_meta.trace_id` with the call; the server checks its format
(`[A-Za-z0-9._:-]{1,128}`) or creates one. The connector sends it to the Alarm API as `x-trace-id` and `trace_id`
headers, and every result carries it in `meta.trace_id`, so one id links the copilot, the MCP server and the API logs.

**Input validation.** Inputs are typed (pydantic): ids must match `^[A-Za-z0-9._-]{1,64}$`, numbers have ranges,
lists have length limits and choices are enums. Invalid arguments are rejected before any API call. Ids are also
URL-escaped when placed in a path, so `../x` cannot change the route.

**Output validation.** Every API response is validated against the tool's output schema before it is returned.
A response that does not match is reported as `[INVALID_API_RESPONSE]` instead of being passed on.

**Timeouts and retries.** Each API call times out after `ALARM_API_TIMEOUT_SECONDS` (default 10 s). Rate limiting
(429), server errors (5xx), network errors and timeouts are retried up to `ALARM_API_MAX_RETRIES` times (default 3)
with exponential backoff (0.5 s, 1 s, 2 s, capped at 8 s) or the delay in `Retry-After`. 400, 401, 403, 404 and
422 are not retried. All tools are read-only, so retrying is safe.

**Errors.** A failed call returns an MCP tool error (`isError: true`) whose text starts with a stable code, says how
to recover and ends with the trace id:

| Code | Cause | Retried |
|---|---|---|
| `[INVALID_INPUT]` | Arguments rejected by the tool or the API (400/422), with the problems listed | no |
| `[NOT_FOUND]` | Unknown asset, alarm or calculation (404), with a hint such as "Use search_assets ..." | no |
| `[AUTH_FAILED]` | The Alarm API rejected the server's token (401/403): a configuration problem | no |
| `[RATE_LIMITED]` | The Alarm API kept throttling (429) after all retries | yes |
| `[UPSTREAM_UNAVAILABLE]` | 5xx, network failure or timeout after all retries | yes |
| `[INVALID_API_RESPONSE]` | The API answered, but not in the documented shape | no |
| `[API_ERROR]` | Any other API error | no |

**Logging.** One structured JSON line per tool call with `trace_id`, `mcp_server`, `tool`, `outcome`, `error_code`,
`duration_ms`, `api_calls` and `retries`; the connector logs each API call with status and attempt number.
"""


def type_of(schema: dict[str, Any], defs: dict[str, Any]) -> str:
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        target = defs.get(name, {})
        return type_of(target, defs) if "enum" in target else name
    if "anyOf" in schema:
        return " \\| ".join(type_of(s, defs) for s in schema["anyOf"])
    if "enum" in schema:
        return " \\| ".join(json.dumps(v) for v in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind == "array":
        return f"list[{type_of(schema.get('items', {}), defs)}]"
    if kind == "string" and schema.get("format") == "date-time":
        return "datetime"
    return str(kind or "object")


def constraints(schema: dict[str, Any]) -> str:
    parts = []
    for key, label in (
        ("minimum", ">= "),
        ("maximum", "<= "),
        ("minLength", "min length "),
        ("maxLength", "max length "),
    ):
        if key in schema:
            parts.append(f"{label}{schema[key]}")
    for key, label in (("minItems", "min items "), ("maxItems", "max items ")):
        if key in schema:
            parts.append(f"{label}{schema[key]}")
    for option in schema.get("anyOf", []):
        parts.extend(p for p in [constraints(option)] if p)
    return ", ".join(parts)


def fields_table(schema: dict[str, Any], with_required: bool) -> str:
    defs = schema.get("$defs", {})
    props = schema.get("properties", {})
    if not props:
        return "_No arguments._\n"
    required = set(schema.get("required", []))
    head = "| Field | Type | Required | Default | Description |\n|---|---|---|---|---|\n"
    if not with_required:
        head = "| Field | Type | Description |\n|---|---|---|\n"
    rows = []
    for name, prop in props.items():
        options = prop.get("anyOf", [])  # an optional field keeps its description on the non-null option
        desc = prop.get("description") or next((o["description"] for o in options if o.get("description")), "")
        desc = " ".join(desc.split())
        limits = constraints(prop)
        desc = f"{desc} ({limits})" if desc and limits else desc or limits
        kind = type_of(prop, defs)
        if with_required:
            default = json.dumps(prop["default"]) if "default" in prop else ""
            rows.append(f"| `{name}` | {kind} | {'yes' if name in required else 'no'} | {default} | {desc} |")
        else:
            rows.append(f"| `{name}` | {kind} | {desc} |")
    return head + "\n".join(rows) + "\n"


def trim(value: Any) -> Any:
    if isinstance(value, list):
        kept = [trim(v) for v in value[:MAX_ITEMS]]
        return kept + ([f"... {len(value) - MAX_ITEMS} more"] if len(value) > MAX_ITEMS else [])
    if isinstance(value, dict):
        return {k: trim(v) for k, v in value.items()}
    if isinstance(value, str) and len(value) > MAX_TEXT:
        return value[:MAX_TEXT] + " ..."
    return value


async def main() -> None:
    logging.disable(logging.WARNING)  # the servers' request logs are not part of the catalog
    simulator = create_app(SimulatorSettings(api_token=TOKEN))
    settings = ClientSettings(base_url="http://simulator", token=TOKEN, backoff_seconds=0)
    transport = httpx.ASGITransport(app=simulator)
    server = build_server(api_client_factory=lambda: AlarmApiClient(settings, transport=transport))

    async with Client(server) as client:
        tools = (await client.list_tools()).tools

        async def call(name: str, args: dict[str, Any]) -> dict[str, Any]:
            result = await client.call_tool(name, args, meta=TRACE)
            if result.is_error:
                raise RuntimeError(f"{name} failed: {result.content[0].text}")
            return result.structured_content

        # Real ids for the alarm-based examples.
        vib = await call("get_alarms", {"asset_id": "AST-BFP-101", "alarm_codes": ["PMP-VIB-HI"], "page_size": 1})
        active = await call("get_alarms", {"asset_id": "AST-BFP-102", "status": "active", "page_size": 1})
        examples = dict(STATIC_EXAMPLES)
        examples["get_alarm_details"] = {"alarm_id": vib["alarms"][0]["alarm_id"]}
        examples["score_alarm_priority"] = {"alarm_id": active["alarms"][0]["alarm_id"]}
        examples["get_operator_recommendations"] = {"alarm_id": vib["alarms"][0]["alarm_id"]}

        index_rows, sections = [], []
        for tool in tools:
            args = examples[tool.name]
            response = await call(tool.name, args)
            calls = response["meta"]["api_calls"]
            endpoint = ", then ".join(f"`{c['method']} {c['path']}`" for c in calls if c["path"] != "/health")
            ann = tool.annotations
            hints = ", ".join(
                label
                for flag, label in ((ann.read_only_hint, "read-only"), (ann.idempotent_hint, "idempotent"))
                if ann and flag
            )
            purpose = " ".join((tool.description or "").split())
            invocation = json.dumps({"name": tool.name, "arguments": args}, indent=2, ensure_ascii=False)
            index_rows.append(f"| [`{tool.name}`](#{tool.name}) | {endpoint} | {tool.title} |")  # GitHub keeps "_"
            schemas = (
                f"```json\n{json.dumps(tool.input_schema, indent=2, ensure_ascii=False)}\n```\n\n"
                f"```json\n{json.dumps(tool.output_schema or {}, indent=2, ensure_ascii=False)}\n```\n"
            )
            sections.append(
                f"### {tool.name}\n\n"
                f"**{tool.title}** ({hints}). {purpose}\n\n"
                f"**Source-system operation:** {endpoint}\n\n"
                f"**Input schema**\n\n{fields_table(tool.input_schema, with_required=True)}\n"
                f"**Output schema** (every result also has `meta`: the trace id and the API calls made)\n\n"
                f"{fields_table(tool.output_schema or {}, with_required=False)}\n"
                f"<details><summary>Full JSON Schemas (input, then output), as the server publishes them</summary>"
                f"\n\n{schemas}\n</details>\n\n"
                f"**Example invocation**\n\n```json\n{invocation}\n```\n\n"
                f"**Example response** (lists shortened to {MAX_ITEMS} items)\n\n"
                f"```json\n{json.dumps(trim(response), indent=2, ensure_ascii=False)}\n```\n"
            )

        error = await client.call_tool("get_asset_metadata", {"asset_id": "AST-NOPE"}, meta=TRACE)
        invalid = await client.call_tool(
            "get_alarm_trends", {"lookback_days": 30, "start_time": "2026-06-01T00:00:00Z"}
        )

    doc = (
        COMMON
        + "\n## Example errors\n\n"
        + "Unknown id (`get_asset_metadata` with `AST-NOPE`):\n\n```text\n"
        + error.content[0].text
        + "\n```\n\nConflicting arguments (`get_alarm_trends` with both `lookback_days` and `start_time`):\n\n```text\n"
        + invalid.content[0].text
        + "\n```\n\n## Tools\n\n| Tool | Alarm API endpoint | Title |\n|---|---|---|\n"
        + "\n".join(index_rows)
        + "\n\n"
        + "\n".join(sections)
    )
    OUT.write_text(doc, encoding="utf-8")
    print(f"wrote {OUT} ({len(tools)} tools)")


if __name__ == "__main__":
    asyncio.run(main())
