"""Generate docs/rag-examples.md: real retrieved chunks, citations, metadata and edge cases.

    uv run python -m rag.ingestion          # build the index first
    uv run python scripts/gen_rag_examples.py

Uses the same index and retriever as the copilot, so the scores, citations and confidence levels shown
in the document are what the running system produces.
"""

import json
import logging
from pathlib import Path

from rag.config import RagSettings
from rag.index_store import load_index
from rag.retrieval import RetrievalFilters, Retriever, render_context

OUT = Path(__file__).resolve().parents[1] / "docs" / "rag-examples.md"

QUERIES = [
    (
        "The acceptance scenario: the procedure for the top alarm",
        "pump High Vibration (PMP-VIB-HI) operating procedure",
        RetrievalFilters(doc_types=["operating_procedure"], alarm_codes=["PMP-VIB-HI"], site="NorthPlant"),
        2,
    ),
    (
        "Safety before a field inspection",
        "lockout and isolation before opening or inspecting a pump",
        RetrievalFilters(doc_types=["safety_instruction"]),
        1,
    ),
    (
        "Which guidance governs when the API's advice conflicts with a procedure",
        "recommendation conflicts with an approved operating procedure, which one governs",
        RetrievalFilters(doc_types=["alarm_philosophy"]),
        1,
    ),
    (
        "A plain-language question with no filters",
        "the feed pump is shaking and the motor bearing is hot, what should I check?",
        None,
        3,
    ),
]


def passage_table(result) -> str:
    rows = [
        "| Key | Citation | Document type | Dense | Keyword | Fused | Matched terms |",
        "|---|---|---|---:|---:|---:|---|",
    ]
    for p in result.passages:
        rows.append(
            f"| {p.citation.key} | {p.citation.label} | {p.citation.doc_type} | {p.dense_score:.3f} | "
            f"{p.keyword_score:.2f} | {p.score:.4f} | {', '.join(p.matched_terms) or '-'} |"
        )
    return "\n".join(rows)


def main() -> None:
    logging.disable(logging.WARNING)
    settings = RagSettings()
    retriever = Retriever.from_settings(settings)
    index = load_index(settings.index_dir)
    manifest = index.manifest
    out = [
        "# RAG examples",
        "",
        "Generated by `scripts/gen_rag_examples.py` from the real index "
        f"({manifest['document_count']} documents, {manifest['chunk_count']} chunks, embedder "
        f"`{manifest['embedder']}`). See [rag-design.md](rag-design.md) for how retrieval works.",
        "",
        "Scores: **Dense** is the cosine similarity of the bge embeddings (0-1), **Keyword** is BM25 relative to the "
        "best keyword hit, **Fused** is the Reciprocal Rank Fusion score plus the small authority and alarm-code "
        "boosts. Passages with a dense score below 0.55 are never used as evidence.",
        "",
        "## Example retrieved chunks",
        "",
    ]
    for title, query, filters, k in QUERIES:
        result = retriever.search(query, k=k, filters=filters)
        shown = json.dumps(filters.model_dump(exclude_none=True, exclude_defaults=True)) if filters else "none"
        out += [
            f"### {title}",
            "",
            f"Query: `{query}`  ",
            f"Filters: `{shown}`  ",
            f"Confidence: **{result.confidence}** (top dense score {result.top_dense_score}), "
            f"{result.latency_ms:.0f} ms",
            "",
            passage_table(result),
            "",
        ]
        top = result.passages[0]
        out += [f"Top passage `{top.chunk_id}`:", "", "> " + " ".join(top.text.split()), ""]

    low = retriever.search("What is the capital of France?", k=3)
    out += [
        "## Low-confidence and no-result handling",
        "",
        "A question the documents cannot answer:",
        "",
        "```json",
        json.dumps(
            {
                "query": low.query,
                "confidence": low.confidence,
                "top_dense_score": low.top_dense_score,
                "passages": [p.citation.label for p in low.passages],
                "message": low.message,
            },
            indent=2,
            ensure_ascii=False,
        ),
        "```",
        "",
        "No passage reaches the 0.55 relevance floor, so nothing is used as evidence; the copilot says what it could "
        "not establish instead of guessing.",
        "",
    ]

    hidden = retriever.search(
        "seal supplier operating note", k=3, filters=RetrievalFilters(doc_ids=["VENDOR-NOTE-009"])
    )
    flagged = [c for c in index.chunks if c.injection_flag]
    out += [
        "## Prompt-injection quarantine",
        "",
        "`VENDOR-NOTE-009` contains a planted instruction for AI assistants in section 3. Ingestion flags that "
        "section; normal searches never return it:",
        "",
        "```json",
        json.dumps(
            {
                "query": hidden.query,
                "filters": {"doc_ids": ["VENDOR-NOTE-009"]},
                "passages": [p.citation.label for p in hidden.passages],
                "quarantined_withheld": hidden.quarantined_withheld,
            },
            indent=2,
            ensure_ascii=False,
        ),
        "```",
        "",
        "The flagged chunk stays in the index for audit (`include_quarantined=True`) with the reasons it was flagged:",
        "",
        "| Chunk | Reasons |",
        "|---|---|",
        *[f"| `{c.chunk_id}` | {', '.join(c.injection_reasons)} |" for c in flagged],
        "",
    ]

    sample = next(c for c in index.chunks if c.doc_id == "SOP-BFP-001" and c.section_number == "4.1")
    record = sample.model_dump()
    record["text"] = " ".join(record["text"].split())[:200] + " ..."
    first = retriever.search(QUERIES[0][1], k=1, filters=QUERIES[0][2]).passages[0]
    out += [
        "## Chunk metadata",
        "",
        "Every chunk in `rag/index/chunks.jsonl` carries what is needed to filter, rank and cite it "
        "(text shortened here):",
        "",
        "```json",
        json.dumps(record, indent=2, ensure_ascii=False),
        "```",
        "",
        "## Citation",
        "",
        "The citation built for a retrieved passage (shown in the GUI's Sources tab and as `[S1]` in the answer):",
        "",
        "```json",
        json.dumps(first.citation.model_dump(), indent=2, ensure_ascii=False),
        "```",
        "",
        "How passages reach the language model: delimited and explicitly marked as untrusted:",
        "",
        "```text",
        render_context([(first.citation, " ".join(first.text.split())[:300] + " ...")]),
        "```",
        "",
        "## Document metadata",
        "",
        "From each document's front matter, recorded in `rag/index/manifest.json`:",
        "",
        "| Document | Type | Sections | Chunks | Quarantined |",
        "|---|---|---:|---:|---:|",
        *[
            f"| {d['doc_id']} | {d['doc_type']} | {d['sections']} | {d['chunks']} | {d['flagged_chunks']} |"
            for d in manifest["documents"]
        ],
        "",
    ]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
